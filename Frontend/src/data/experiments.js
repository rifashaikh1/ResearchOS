function rocCurve(auc) {
  const pts = [{ fpr: 0, tpr: 0 }];
  for (let i = 1; i <= 19; i++) {
    const fpr = i / 20;
    const tpr = Math.min(1, fpr + (auc - 0.5) * 2 * (1 - fpr) + (Math.random() - 0.5) * 0.04);
    pts.push({ fpr: parseFloat(fpr.toFixed(3)), tpr: parseFloat(Math.max(pts[pts.length - 1].tpr, tpr).toFixed(3)) });
  }
  pts.push({ fpr: 1, tpr: 1 });
  return pts;
}

function epochData(epochs, finalAcc) {
  return Array.from({ length: epochs }, (_, i) => {
    const t = (i + 1) / epochs;
    const curve = 1 - Math.exp(-4 * t);
    return {
      epoch: i + 1,
      trainLoss: parseFloat((1.2 * (1 - curve * 0.92) + Math.random() * 0.02).toFixed(4)),
      valLoss: parseFloat((1.3 * (1 - curve * 0.85) + Math.random() * 0.03).toFixed(4)),
      trainAcc: parseFloat(Math.min(100, finalAcc + 2 + (curve * (finalAcc - 30)) + (30 - 30 * (1 - t))).toFixed(2)),
      valAcc: parseFloat(Math.min(100, finalAcc - 1 + curve * (finalAcc - 35)).toFixed(2)),
    };
  });
}

